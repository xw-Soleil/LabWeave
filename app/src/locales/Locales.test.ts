import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import YAML from "yaml";

const directory = fileURLToPath(new URL(".", import.meta.url));
const locales = readdirSync(directory).filter((name) => name.endsWith(".yml"));

describe("application locale resources", () => {
  it.each(locales)("parses %s and keeps rename messages in the root research namespace", (name) => {
    const locale = YAML.parse(readFileSync(new URL(name, import.meta.url), "utf8"));
    expect(locale.settings?.categories?.research?.title).toBeTypeOf("string");
    expect(locale.settings.rename).toBeUndefined();
    // zh_TW is generated by Vite; the handwritten files must supply these keys directly.
    if (name === "zh_TW.yml") return;
    for (const key of [
      "title",
      "description",
      "invalid",
      "busy",
      "outside",
      "exists",
      "incompleteScan",
      "changed",
      "rollbackFailed",
      "followupFailed",
    ]) {
      expect(locale.research?.rename?.[key], `${name}: research.rename.${key}`).toBeTypeOf("string");
    }
    expect(locale.keyBinds.straightenSelectedEdges.title).toBeTypeOf("string");
    expect(locale.contextMenu.alignObjects).toBeTypeOf("string");
    expect(locale.contextMenu.alignSelectionHint).toBeTypeOf("string");
    for (const key of [
      "open",
      "reveal",
      "delete",
      "deleteDescription",
      "deleted",
      "restore",
      "restoreLast",
      "restored",
      "restoreConflict",
      "trashEmpty",
      "busy",
      "outside",
      "invalidTrash",
    ]) {
      expect(locale.research?.fileMenu?.[key], `${name}: research.fileMenu.${key}`).toBeTypeOf("string");
    }
  });
});
